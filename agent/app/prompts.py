"""Шаблоны промптов для ресёрча X (Twitter) через Grok."""
from __future__ import annotations

SYSTEM_PROMPT = (
    "Ты — исследовательский агент с доступом к живому поиску по X (Twitter). "
    "Всегда используй актуальный поиск по X, а не общие знания из обучения. "
    "Бери только реально существующие посты: не выдумывай ссылки, авторов и метрики. "
    "Отвечай СТРОГО в формате JSON: без markdown-обёрток, без пояснений, "
    "без любого текста до или после JSON-массива."
)


def build_user_prompt(
    topic_name: str,
    query: str,
    min_likes: int,
    min_views: int,
    min_reposts: int,
    max_posts: int,
) -> str:
    return f"""Найди через поиск X (Twitter) свежие посты (за последние 24 часа) по теме «{topic_name}».
Поисковые ориентиры: {query}.

Критерии отбора — пост должен набирать примерно:
- лайков >= {min_likes}
- просмотров >= {min_views}
- репостов >= {min_reposts}
Если какую-то метрику узнать не удалось — ставь 0, но такие посты включай только если они явно вирусные.

Верни максимум {max_posts} лучших постов, отсортированных по лайкам (от большего к меньшему).

Формат ответа — строго один JSON-массив. Каждый элемент:
{{
  "author": "@handle автора",
  "text": "полный текст поста",
  "url": "https://x.com/.../status/... (прямая ссылка на пост)",
  "likes": 0,
  "reposts": 0,
  "views": 0,
  "posted_at": "время публикации, как показано в X",
  "summary": "1-2 предложения на русском: о чём пост и почему он важен"
}}

Если подходящих постов нет — верни пустой массив []."""
